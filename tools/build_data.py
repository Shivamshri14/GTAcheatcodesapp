T={'X':'X','O':'Circle','S':'Square','T':'Triangle'}
def ps(s): return [ {'X':'Cross','O':'Circle','S':'Square','T':'Triangle','U':'Up','D':'Down','L':'Left','R':'Right'}.get(t,t) for t in s.split()]
XB={'Cross':'A','Circle':'B','Square':'X','Triangle':'Y','L1':'LB','R1':'RB','L2':'LT','R2':'RT'}
def xb(seq): return [XB.get(t,t) for t in seq]
def c(name,cat,p=None,pc=None,note=None,phone=None):
    d={'name':name,'cat':cat}
    if p: d['ps']=ps(p); d['xbox']=xb(d['ps'])
    if pc: d['pc']=pc
    if phone: d['phone']=phone
    if note: d['note']=note
    return d
